# -*- coding: utf-8 -*-
"""Update the 6 prices.sci99.com tabs of the 原料 spreadsheet.

Each tab carries its own detail url (row 1, diid/ppid), so the page is the
series: parse the history table (日期/最低价/最高价/平均价), keep rows whose
市场 and 规格型号 fit the key stored on the sheet, and write them back under
the sheet's own name/spec/market/dtype so a source rename cannot drift the
tab.

Layouts handled: 10 cols (棕榈油 - no 比例 column), 11 (玉米/豆粕) and 17
(维生素E - the FX block K..Q is refilled by raw_lib from the column
templates). 涨跌/比例 are regenerated by raw_lib.stamp.

Quota: one values_batch_get + one values_batch_update.
The two vip.sci99.com PDF tabs are handled by update_raw_sci99_pdf.py.
"""
import io
import json
import os
import re
import sys
import time
from datetime import datetime

if __name__ == '__main__' and __package__ is None:
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', errors='replace', line_buffering=True)
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from playwright.sync_api import sync_playwright

import newsheet_lib as NS
import raw_lib as RL
from update_from_detail_pages import extract_detail_rows

COOKIES = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'sci99_cookies.json')


def num(v):
    s = str(v or '').strip().replace('\xa0', '').replace(' ', '')
    if not s or s in ('-', '--', '请登录'):
        return ''
    s = s.replace('▲', '').replace('▼', '')
    if re.fullmatch(r'-?\d{1,3}(\.\d{3})+(,\d+)?', s):      # 4.000,00
        s = s.replace('.', '').replace(',', '.')
    elif re.fullmatch(r'-?\d+,\d+', s):
        s = s.replace(',', '.')
    elif ',' in s:
        s = s.replace(',', '')
    try:
        f = float(s)
    except ValueError:
        return ''
    return int(f) if f == int(f) else round(f, 4)


def _date(s):
    s = str(s or '').strip()
    for fmt in ('%Y/%m/%d', '%Y-%m-%d', '%m/%d/%Y', '%Y.%m.%d'):
        try:
            return datetime.strptime(s, fmt).strftime('%Y-%m-%d')
        except ValueError:
            continue
    return ''


def _digits(s):
    return set(re.findall(r'\d+', str(s or '')))


def spec_ok(sheet_spec, src_spec):
    a = str(sheet_spec or '').strip()
    b = str(src_spec or '').strip()
    if not a or not b:
        return True
    if a == b or a in b or b in a:
        return True
    da, db = _digits(a), _digits(b)
    return bool(da) and da == db


def market_ok(sheet_market, src_market):
    a = str(sheet_market or '').strip()
    b = str(src_market or '').strip()
    if not a or not b:
        return True
    return a == b or a in b or b in a


def parse_series(raw_rows, market, spec):
    """-> {iso_date: (min, max, avg)} for the series this tab tracks."""
    header, start = None, 0
    for i, r in enumerate(raw_rows):
        j = ' '.join(str(x) for x in r)
        if '日期' in j and '平均价' in j:
            header, start = r, i + 1
            break
    if header is None:
        return {}
    col = {}
    for i, h in enumerate(header):
        h = str(h).strip()
        if h.endswith('日期') or h == '日期':
            col['date'] = i
        elif h == '市场':
            col['market'] = i
        elif h == '规格型号':
            col['spec'] = i
        elif h == '最低价':
            col['min'] = i
        elif h == '最高价':
            col['max'] = i
        elif h == '平均价' or h.startswith('平均价'):
            col['avg'] = i
    if 'date' not in col or 'avg' not in col:
        return {}
    out = {}
    for r in raw_rows[start:]:
        def cell(k, default=''):
            i = col.get(k, -1)
            return r[i] if 0 <= i < len(r) else default
        d = _date(cell('date'))
        if not d:
            continue
        if not market_ok(market, cell('market')):
            continue
        if not spec_ok(spec, cell('spec')):
            continue
        avg = num(cell('avg'))
        if avg == '':
            continue
        out.setdefault(d, (num(cell('min')), num(cell('max')), avg))
    return out


def key_of(rows, meta):
    old = RL.data_rows(rows, meta)
    if not old:
        return None
    k = old[0]
    rem = k[10] if len(k) > 10 else ''
    return {
        'name': k[1], 'spec': k[2], 'market': k[3], 'dtype': k[4],
        'width': meta['width'],
        'remark': rem if isinstance(rem, str) else '',
        'price_col': meta['price_col'],
    }


def to_fresh(iso, trip, k):
    d = datetime.strptime(iso, '%Y-%m-%d')
    row = [''] * k['width']
    row[0] = f'{d.month}/{d.day}/{d.year}'
    row[1], row[2], row[3], row[4] = k['name'], k['spec'], k['market'], k['dtype']
    row[5], row[6] = trip[0], trip[1]
    row[k['price_col']] = trip[2]
    if k['width'] > 10:
        row[10] = k['remark']
    return row


def main():
    sh = RL.open_sh()
    allt = RL.all_titles(sh)
    res = RL.retry(sh.values_batch_get, [f"'{t}'!A1:A1" for t in allt],
                   params={'valueRenderOption': 'FORMULA'})
    titles, urls = [], {}
    for t, v in zip(allt, res['valueRanges']):
        vals = v.get('values') or [['']]
        u = vals[0][0] if vals and vals[0] else ''
        if 'prices.sci99.com' in str(u):
            titles.append(t)
            urls[t] = u
    titles.sort()
    print(f'sci99 detail: {len(titles)} tabs')
    if not titles:
        print('DONE raw_sci99')
        return

    grid = RL.read_grid(sh, titles)
    metas, keys, sheet_max = {}, {}, {}
    for t in titles:
        m = RL.analyze(grid[t])
        if m is None:
            print(f'  WARN {t}: no header, skipped')
            continue
        k = key_of(grid[t], m)
        if k is None:
            print(f'  WARN {t}: no data rows, skipped')
            continue
        metas[t], keys[t] = m, k
        dates = []
        for r in RL.data_rows(grid[t], m):
            d = NS.date_text(r[0])
            if d:
                try:
                    dates.append(datetime.strptime(d, '%m/%d/%Y').strftime('%Y-%m-%d'))
                except ValueError:
                    pass
        sheet_max[t] = max(dates) if dates else ''

    fresh = {t: [] for t in titles}
    stats = {}
    cookies = json.load(open(COOKIES, encoding='utf-8'))
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True)
        ctx = browser.new_context(viewport={'width': 1400, 'height': 900})
        try:
            ctx.add_cookies(cookies)
        except Exception as e:
            print('cookie err', e)
        page = ctx.new_page()
        fail = 0
        for t in titles:
            if t not in keys:
                continue
            raw, title, final_url = extract_detail_rows(page, urls[t])
            if not raw:
                fail += 1
                print(f'  {t}: no rows (title={title!r})')
                if fail >= 4:
                    print('  4 consecutive failures - site blocked, aborting')
                    break
                time.sleep(20)
                continue
            fail = 0
            k = keys[t]
            series = parse_series(raw, k['market'], k['spec'])
            smax = sheet_max[t]
            old_price = {}
            for r in RL.data_rows(grid[t], metas[t]):
                dd = NS.date_text(r[0])
                if not dd:
                    continue
                try:
                    dd = datetime.strptime(dd, '%m/%d/%Y').strftime('%Y-%m-%d')
                except ValueError:
                    continue
                old_price.setdefault(dd, RL._plain(r[metas[t]['price_col']]))
            news = [d for d in sorted(series, reverse=True) if d > smax]
            diff = [d for d in sorted(series, reverse=True)
                    if d in old_price and old_price[d] is not None
                    and old_price[d] != series[d][2]]
            stats[t] = (len(series), len(news), len(diff), title)
            print(f'  {t}: {len(series)} source dates, +{len(news)} new, {len(diff)} older prices differ, '
                  f'latest {max(series) if series else None} (sheet {smax}) title={title!r}')
            for iso in sorted(series, reverse=True):
                fresh[t].append(to_fresh(iso, series[iso], k))
        browser.close()

    blocks, first_row, old_end = {}, {}, {}
    for t in titles:
        if t not in keys:
            continue
        built, meta, err = RL.build(grid[t], fresh[t], metas[t])
        if err:
            print(f'  FAIL {t}: {err}')
            continue
        old_n = len(RL.data_rows(grid[t], metas[t]))
        new_n = len(built)
        if new_n != old_n or fresh[t]:
            blocks[t] = built
            first_row[t] = metas[t]['first']
            old_end[t] = metas[t]['first'] + old_n - 1
            if fresh[t]:
                print(f'  {t}: rows {old_n} -> {new_n}')
    if not blocks:
        print('nothing new')
        print('DONE raw_sci99')
        return
    if '--dry' in sys.argv:
        print(f'[dry] would write {len(blocks)} tabs: '
              + ', '.join(f'{t}:{len(v)}' for t, v in sorted(blocks.items())))
        print('DONE raw_sci99')
        return
    n = RL.write_all(sh, blocks, first_row, old_end=old_end)
    print(f'wrote {n} tabs in 1 call')
    print('DONE raw_sci99')


if __name__ == '__main__':
    main()
